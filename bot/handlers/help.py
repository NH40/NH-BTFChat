def _menu() -> InlineKeyboardMarkup:
    buttons = [InlineKeyboardButton(text=title, callback_data=f"{CB_HELP}{code}") for code, title, _ in SECTIONS]
    rows = [buttons[i:i + 2] for i in range(0, len(buttons), 2)]
    if settings.mini_app_url:
        rows.append([InlineKeyboardButton(text="📋 Открыть BTF", web_app=WebAppInfo(url=settings.mini_app_url))])
    return InlineKeyboardMarkup(inline_keyboard=rows)


def _back() -> InlineKeyboardMarkup:
    return InlineKeyboardMarkup(inline_keyboard=[[InlineKeyboardButton(text="◀️ К разделам", callback_data=CB_HELP)]])


MENU_TEXT = "📖 <b>Гайд по боту BTF</b>\n\nВыбери раздел. Новичку — начать с «🚀 С чего начать»."


async def send_guide(message: Message, session: AsyncSession) -> None:
    if await staff.role_of(session, message.from_user.id) is None:
        await message.answer(NOT_STAFF)
        return
    await message.answer(MENU_TEXT, reply_markup=_menu())


@router.message(CommandStart(deep_link=True), F.chat.type == "private")
async def start_help(message: Message, command: CommandObject, session: AsyncSession) -> None:
    if command.args == START_PARAM:
        await send_guide(message, session)


@router.message(Command("help"), F.chat.type == "private")
async def cmd_help(message: Message, session: AsyncSession) -> None:
    await send_guide(message, session)


@router.message(Command("help"), F.chat.type.in_({"group", "supergroup"}))
async def cmd_help_group(message: Message, bot: Bot) -> None:
    me = await bot.me()
    kb = InlineKeyboardMarkup(inline_keyboard=[[
        InlineKeyboardButton(text="📖 Полный гайд", url=f"https://t.me/{me.username}?start={START_PARAM}"),
    ]])
    await message.reply(GROUP_HELP, reply_markup=kb)


@router.callback_query(F.data.startswith(CB_HELP))
async def cb_help(callback: CallbackQuery, session: AsyncSession) -> None:
    if await staff.role_of(session, callback.from_user.id) is None:
        await callback.answer(NOT_STAFF, show_alert=True)
        return
    code = callback.data.removeprefix(CB_HELP)
    if code and code not in _BY_CODE:
        await callback.answer()
        return
    text, kb = (_BY_CODE[code][1], _back()) if code else (MENU_TEXT, _menu())
    try:
        await callback.message.edit_text(text, reply_markup=kb, disable_web_page_preview=True)
    except TelegramBadRequest:
        pass  # то же самое содержимое — Telegram отказывает «message is not modified»
    await callback.answer()
